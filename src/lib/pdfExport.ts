/**
 * Add budgets data to PDF document
 */
async function addBudgetsToPDF(
  pdf: jsPDF,
  userId: string,
  startY: number,
  pageHeight: number
): Promise<number> {
  let yPosition = startY;

  // Check if we need a new page
  if (yPosition > pageHeight - 100) {
    pdf.addPage();
    yPosition = 20;
  }

  // Add budgets section header
  pdf.setFontSize(16);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Budgets', 20, yPosition);
  yPosition += 10;

  // Fetch budgets data
  const { data: budgets, error } = await supabase
    .from('budgets')
    .select('*')
    .eq('user_id', userId)
    .order('category');

  if (error) {
    pdf.setFontSize(12);
    pdf.text('Error loading budgets data', 20, yPosition);
    return yPosition + 20;
  }

  if (!budgets || budgets.length === 0) {
    pdf.setFontSize(12);
    pdf.text('No budgets found', 20, yPosition);
    return yPosition + 20;
  }

  // Add table headers
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Category', 20, yPosition);
  pdf.text('Budget (KES)', 70, yPosition);
  pdf.text('Spent (KES)', 110, yPosition);
  pdf.text('Remaining (KES)', 150, yPosition);
  yPosition += 5;

  // Add line under headers
  pdf.line(20, yPosition, 190, yPosition);
  yPosition += 5;

  // Add budget rows
  pdf.setFont('helvetica', 'normal');
  let totalBudget = 0;
  let totalSpent = 0;

  for (const budget of budgets) {
    // Check if we need a new page
    if (yPosition > pageHeight - 30) {
      pdf.addPage();
      yPosition = 20;
    }

    const budgetAmount = Number(budget.limit_amount);
    const spentAmount = Number(budget.spent_amount || 0);
    const remaining = budgetAmount - spentAmount;

    pdf.text(budget.category, 20, yPosition);
    pdf.text(budgetAmount.toLocaleString(), 70, yPosition);
    pdf.text(spentAmount.toLocaleString(), 110, yPosition);
    pdf.text(remaining.toLocaleString(), 150, yPosition);
    
    totalBudget += budgetAmount;
    totalSpent += spentAmount;
    yPosition += 8;
  }

  // Add totals
  yPosition += 5;
  pdf.line(20, yPosition, 190, yPosition);
  yPosition += 5;
  pdf.setFont('helvetica', 'bold');
  pdf.text(`Total Budget: KES ${totalBudget.toLocaleString()}`, 20, yPosition);
  yPosition += 5;
  pdf.text(`Total Spent: KES ${totalSpent.toLocaleString()}`, 20, yPosition);
  yPosition += 5;
  pdf.text(`Total Remaining: KES ${(totalBudget - totalSpent).toLocaleString()}`, 20, yPosition);
  
  return yPosition + 20;
}

/**
 * Export specific page content as PDF using html2canvas
 * @param elementId - ID of the element to export
 * @param filename - Name of the PDF file
 */
export const exportElementToPDF = async (elementId: string, filename: string): Promise<void> => {
  try {
    const element = document.getElementById(elementId);
    if (!element) {
      throw new Error(`Element with ID "${elementId}" not found`);
    }

    // Create canvas from element
    const canvas = await html2canvas(element, {
      scale: 2,
      useCORS: true,
      logging: false,
    });

    // Create PDF
    const pdf = new jsPDF('p', 'mm', 'a4');
    const imgData = canvas.toDataURL('image/png');
    
    const pdfWidth = pdf.internal.pageSize.getWidth() - 20; // 10mm margin on each side
    const pdfHeight = (canvas.height * pdfWidth) / canvas.width;
    
    pdf.addImage(imgData, 'PNG', 10, 10, pdfWidth, pdfHeight);
    pdf.save(filename);

  } catch (error) {
    console.error('Error exporting element to PDF:', error);
    throw new Error('Failed to export content to PDF');
  }
};
